"""Document storage for the two customer PDFs (certificate and registry document).

One interface, two backends: local disk (development) and a private S3 bucket (production, see s3_storage.py).
The database only ever stores an opaque, server-generated key; the client never chooses a storage location.
"""
from __future__ import annotations

import re
import shutil
import uuid
from pathlib import Path
from typing import BinaryIO, Protocol

from fastapi import Response
from fastapi.responses import FileResponse

# New uploads are PDF only. Images stay SERVABLE so records uploaded before this rule keep working.
UPLOAD_TYPES = {".pdf": ("application/pdf", b"%PDF-")}
LEGACY_IMAGE_TYPES = {
    ".png": ("image/png", b"\x89PNG\r\n\x1a\n"),
    ".jpg": ("image/jpeg", b"\xff\xd8\xff"),
    ".jpeg": ("image/jpeg", b"\xff\xd8\xff"),
}
ALLOWED_TYPES = {**UPLOAD_TYPES, **LEGACY_IMAGE_TYPES}
CONTENT_TYPES = {ext: meta[0] for ext, meta in ALLOWED_TYPES.items()}

SUBDIR = "certificates"
# Storage keys are generated by the server and must match this shape; anything else is refused outright.
KEY_RE = re.compile(rf"^{SUBDIR}/[0-9a-f]{{32}}\.(pdf|png|jpg|jpeg)$")
_TAIL_BYTES = 1024


class InvalidCertificate(Exception):
    def __init__(self, message: str, too_large: bool = False):
        super().__init__(message)
        self.message = message
        self.too_large = too_large


class DocumentStorage(Protocol):
    def save_stream(self, extension: str, fileobj: BinaryIO) -> str: ...
    def save(self, extension: str, data: bytes) -> str: ...
    def exists(self, key: str) -> bool: ...
    def delete(self, key: str) -> None: ...
    def download(self, key: str, filename: str, content_type: str, *, attachment: bool) -> Response: ...


CertificateStorage = DocumentStorage  # older name, still imported in a few places


def new_key(extension: str) -> str:
    return f"{SUBDIR}/{uuid.uuid4().hex}{extension}"


def _check(filename: str, size: int, header: bytes, tail: bytes, max_bytes: int, allow_images: bool) -> str:
    ext = Path(filename or "").suffix.lower()
    allowed = ALLOWED_TYPES if allow_images else UPLOAD_TYPES
    if ext not in allowed:
        raise InvalidCertificate("Unsupported file type. Upload a PDF file.")
    if size == 0:
        raise InvalidCertificate("The uploaded file is empty.")
    if size > max_bytes:
        raise InvalidCertificate(
            f"File is too large. Maximum size is {max_bytes / (1024 * 1024):g} MB.", too_large=True
        )
    if not header.startswith(allowed[ext][1]):
        raise InvalidCertificate("File content does not match its file type.")
    if ext == ".pdf" and b"%%EOF" not in tail:
        raise InvalidCertificate("The PDF looks incomplete or damaged. Please export it again and retry.")
    return ".jpg" if ext == ".jpeg" else ext


def validate_certificate(filename: str, data: bytes, max_bytes: int, *, allow_images: bool = False) -> str:
    """Validate an in-memory file; returns the normalized extension or raises InvalidCertificate."""
    return _check(filename, len(data), data[:16], data[-_TAIL_BYTES:], max_bytes, allow_images)


def inspect_stream(filename: str, stream: BinaryIO, max_bytes: int, *, allow_images: bool = False) -> tuple[str, int]:
    """Validate an uploaded file without loading it into memory. Returns (extension, size) and rewinds the stream."""
    stream.seek(0, 2)
    size = stream.tell()
    stream.seek(0)
    header = stream.read(16)
    stream.seek(max(0, size - _TAIL_BYTES))
    tail = stream.read(_TAIL_BYTES)
    stream.seek(0)
    return _check(filename, size, header, tail, max_bytes, allow_images), size


def safe_key(key: str | None) -> str | None:
    return key if key and KEY_RE.match(key) else None


class LocalCertificateStorage:
    """Development storage on local disk. NOT durable on hosts with an ephemeral filesystem."""

    SUBDIR = SUBDIR

    def __init__(self, upload_dir: Path):
        self.root = (upload_dir / SUBDIR).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def save_stream(self, extension: str, fileobj: BinaryIO) -> str:
        key = new_key(extension)
        path = self.root.parent / key
        try:
            with path.open("wb") as out:
                shutil.copyfileobj(fileobj, out, 64 * 1024)
        except Exception:
            path.unlink(missing_ok=True)
            raise
        return key

    def save(self, extension: str, data: bytes) -> str:
        key = new_key(extension)
        (self.root.parent / key).write_bytes(data)
        return key

    def open_path(self, key: str) -> Path | None:
        """Resolve a stored key to a file, refusing anything outside the document directory."""
        if not safe_key(key):
            return None
        path = (self.root.parent / key).resolve()
        if not path.is_relative_to(self.root) or not path.is_file():
            return None
        return path

    def exists(self, key: str) -> bool:
        return self.open_path(key) is not None

    def delete(self, key: str) -> None:
        path = self.open_path(key)
        if path:
            path.unlink(missing_ok=True)

    def download(self, key: str, filename: str, content_type: str, *, attachment: bool) -> Response:
        path = self.open_path(key)
        if path is None:
            raise FileNotFoundError(key)
        return FileResponse(
            path,
            media_type=content_type,
            headers={
                "Content-Disposition": f'{"attachment" if attachment else "inline"}; filename="{filename}"',
                "Cache-Control": "private, no-store",
                "X-Content-Type-Options": "nosniff",
            },
        )
